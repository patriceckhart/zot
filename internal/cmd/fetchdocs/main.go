// Command fetchdocs generates an ignored snapshot of public website docs.
package main

import (
	"bytes"
	"context"
	"crypto/sha256"
	"flag"
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
)

const website = "https://www.zot.sh"

var docLink = regexp.MustCompile(`\]\(https://www\.zot\.sh/docs(?:/([a-z0-9-]+))?\)`)
var pageName = regexp.MustCompile(`^[a-z0-9-]+\.md$`)

func main() {
	out := flag.String("out", "docs/website", "generated snapshot directory")
	allowStale := flag.Bool("allow-stale", false, "allow a validated cached snapshot or repository-only docs if downloading fails")
	timeout := flag.Duration("timeout", 2*time.Minute, "total download timeout")
	flag.Parse()
	ctx, cancel := context.WithTimeout(context.Background(), *timeout)
	defer cancel()
	if err := refresh(ctx, http.DefaultClient, website, *out, *allowStale, os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, "fetch docs:", err)
		os.Exit(1)
	}
}

func refresh(ctx context.Context, client *http.Client, baseURL, out string, allowStale bool, warnings io.Writer) error {
	files, err := fetchSnapshot(ctx, client, baseURL)
	if err != nil {
		if !allowStale {
			return err
		}
		entries, readErr := os.ReadDir(out)
		if os.IsNotExist(readErr) || (readErr == nil && len(entries) == 0) {
			fmt.Fprintf(warnings, "warning: docs refresh failed: %v. No cached website docs, building with repository documentation only.\n", err)
			return nil
		}
		if cacheErr := validateSnapshot(out); cacheErr != nil {
			return fmt.Errorf("%w (bundled documentation cannot be used: %v)", err, cacheErr)
		}
		fmt.Fprintf(warnings, "warning: docs refresh failed: %v. Using validated bundled documentation from %s.\n", err, out)
		return nil
	}
	// Download errors may fall back, but local write errors must remain fatal.
	if err := writeSnapshot(out, files); err != nil {
		return err
	}
	fmt.Printf("Fetched %d website documentation pages\n", len(files)-1)
	return nil
}

func fetchSnapshot(ctx context.Context, client *http.Client, baseURL string) (map[string][]byte, error) {
	index, err := download(ctx, client, baseURL+"/llms.txt")
	if err != nil {
		return nil, err
	}
	names, err := pageNames(string(index))
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{}
	var source strings.Builder
	source.WriteString("Website documentation downloaded from https://www.zot.sh\nGenerated by go run ./internal/cmd/fetchdocs. Do not edit this snapshot directly.\nWebsite pages may describe features newer than this binary. Repository reference docs take precedence.\n\nSHA-256 of downloaded Markdown:\n")
	for _, name := range names {
		data, err := download(ctx, client, baseURL+"/docs/"+name)
		if err != nil {
			return nil, err
		}
		if !bytes.HasPrefix(bytes.TrimSpace(data), []byte("# ")) {
			return nil, fmt.Errorf("%s is not a Markdown documentation page", name)
		}
		files[name] = data
		fmt.Fprintf(&source, "%x  %s\n", sha256.Sum256(data), name)
	}
	files["SOURCE.txt"] = []byte(source.String())
	return files, nil
}

// validateSnapshot checks completeness and hashes before trusting an offline copy.
func validateSnapshot(out string) error {
	source, err := os.ReadFile(filepath.Join(out, "SOURCE.txt"))
	if err != nil {
		return err
	}
	_, hashes, ok := strings.Cut(string(source), "\nSHA-256 of downloaded Markdown:\n")
	if !ok {
		return fmt.Errorf("snapshot hash manifest is missing")
	}
	seen := map[string]bool{}
	for _, line := range strings.Split(strings.TrimSpace(hashes), "\n") {
		fields := strings.Fields(line)
		if len(fields) != 2 || !pageName.MatchString(fields[1]) || seen[fields[1]] {
			return fmt.Errorf("invalid snapshot hash entry %q", line)
		}
		data, err := os.ReadFile(filepath.Join(out, fields[1]))
		if err != nil {
			return err
		}
		if fmt.Sprintf("%x", sha256.Sum256(data)) != fields[0] {
			return fmt.Errorf("snapshot hash mismatch for %s", fields[1])
		}
		seen[fields[1]] = true
	}
	for _, required := range []string{"index.md", "quickstart.md", "tools.md"} {
		if !seen[required] {
			return fmt.Errorf("snapshot is missing %s", required)
		}
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if strings.HasSuffix(entry.Name(), ".md") && !seen[entry.Name()] {
			return fmt.Errorf("snapshot has an unverified page %s", entry.Name())
		}
	}
	return nil
}

func pageNames(index string) ([]string, error) {
	seen := map[string]bool{}
	for _, match := range docLink.FindAllStringSubmatch(index, -1) {
		name := match[1]
		if name == "" {
			name = "index"
		}
		seen[name+".md"] = true
	}
	for _, required := range []string{"index.md", "quickstart.md", "tools.md"} {
		if !seen[required] {
			return nil, fmt.Errorf("website documentation index is missing %s", required)
		}
	}
	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

func download(ctx context.Context, client *http.Client, url string) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	resp, err := client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", url, err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("download %s: HTTP %d", url, resp.StatusCode)
	}
	const maxPageBytes = 2 << 20
	data, err := io.ReadAll(io.LimitReader(resp.Body, maxPageBytes+1))
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", url, err)
	}
	if len(data) > maxPageBytes {
		return nil, fmt.Errorf("download %s: page exceeds %d bytes", url, maxPageBytes)
	}
	return data, nil
}

func writeSnapshot(out string, files map[string][]byte) error {
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		dst := filepath.Join(out, name)
		if old, err := os.ReadFile(dst); err == nil && bytes.Equal(old, files[name]) {
			continue
		}
		if err := os.WriteFile(dst, files[name], 0o644); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(out)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if !entry.IsDir() && strings.HasSuffix(entry.Name(), ".md") && files[entry.Name()] == nil {
			if err := os.Remove(filepath.Join(out, entry.Name())); err != nil {
				return err
			}
		}
	}
	return nil
}
